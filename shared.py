def convert_date(date_str: str) -> str:
    months = {
        'january': '01', 'february': '02', 'march': '03', 'april': '04', 'may': '05',
        'june': '06', 'july': '07', 'august': '08', 'september': '09',
        'october': '10', 'november': '11', 'december': '12'
    }
    date_str = re.sub(r'(\d+)(st|nd|rd|th)\b', r'\1', date_str)
    try:
        day, month = date_str.strip().split()
        day = day.zfill(2)
        month = months[month.lower()]
        return f"{day}.{month}.{datetime.now().year}"
    except Exception:
        return None

def get_container_type_from_header(header_cell):
    """Определяет тип контейнера из заголовка колонки"""
    header = str(header_cell).lower()
    
    if '20gp' in header or '20 gp' in header:
        return '20GP'
    elif '40hc' in header or '40 hc' in header:
        return '40HC'
    elif '20rf' in header or '20 rf' in header:
        return '20RF'
    elif '40rf' in header or '40 rf' in header:
        return '40RF'
    elif '20tank' in header or '20 tank' in header:
        return '20TK'
    elif len(header.split()) == 1:
        return header.upper()
    else:
        return None

def normalize_date(date_str, year=2025):
    """Для обогащения данных (valid_from/valid_to)."""
    if not date_str:
        return ""
    date_str = str(date_str).replace(' ', '').replace(':', '')
    if '.' in date_str:
        parts = date_str.split('.')
        if len(parts) == 3:
            return f"{parts[2]}-{parts[1].zfill(2)}-{parts[0].zfill(2)}"
        elif len(parts) == 2:
            month, day = parts
            return f"{year}-{month.zfill(2)}-{day.zfill(2)}"
        return ""
    elif '-' in date_str:
        parts = date_str.split('-')
        if len(parts) == 3:
            return f"{parts[0]}-{parts[1].zfill(2)}-{parts[2].zfill(2)}"
        return ""
    return ""


def _to_number_or_zero(value):
    import numpy as np
    try:
        if value is None or (isinstance(value, float) and np.isnan(value)):
            return 0
        if isinstance(value, str):
            v = value.replace(" ", "").replace(",", ".")
            v = re.sub(r"[^0-9.\-]", "", v)
            return float(v) if v not in ("", ".", "-") else 0
        return float(value)
    except Exception:
        return 0


def _to_str_or_empty(value):
    try:
        import numpy as np
        if value is None or (isinstance(value, float) and np.isnan(value)):
            return ""
    except Exception:
        if value is None:
            return ""
    return str(value)


def _sanitize_filename(name: str) -> str:
    for ch in '<>:"/\\|?*':
        name = name.replace(ch, "_")
    return name.strip()
