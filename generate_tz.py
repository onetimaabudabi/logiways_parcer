def body(text, indent=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.first_line_indent = Cm(1.25)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    run = p.add_run(text)
    set_font(run, size=12)
    p.paragraph_format.space_after = Pt(4)
    return p

def bullet(text, level=0):
    p = doc.add_paragraph(style="List Bullet")
    p.paragraph_format.left_indent = Cm(1.0 + level * 0.75)
    run = p.add_run(text)
    set_font(run, size=12)
    p.paragraph_format.space_after = Pt(2)
    return p

def add_table_2col(rows_data, col_widths=(6, 10)):
    table = doc.add_table(rows=len(rows_data), cols=2)
    table.style = "Table Grid"
    for i, (left, right) in enumerate(rows_data):
        row = table.rows[i]
        row.cells[0].width = Cm(col_widths[0])
        row.cells[1].width = Cm(col_widths[1])
        p0 = row.cells[0].paragraphs[0]
        p1 = row.cells[1].paragraphs[0]
        r0 = p0.add_run(left)
        r1 = p1.add_run(right)
        set_font(r0, size=11, bold=True)
        set_font(r1, size=11)
    doc.add_paragraph()

